/**
 * Build the browser artifact for @nana-2503/dsh-opencode-usage.
 *
 * 1. Compile `src/index.css` with the Tailwind CLI (utilities only, no
 *    preflight, so the Harness page keeps its own resets).
 * 2. Inline that CSS as a module the client bundle imports as a string.
 * 3. Bundle the TSX entry into the CommonJS shape the Harness module loader
 *    expects, with React taken from the page's module table.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = dirname(fileURLToPath(import.meta.url));
/** `--css-only` refreshes the generated CSS module without bundling (typecheck on a fresh clone). */
const cssOnly = process.argv.includes("--css-only");
const pkg = "@nana-2503/dsh-opencode-usage";
const outFile = join(root, "client.js");

mkdirSync(join(root, "build"), { recursive: true });

execFileSync(process.execPath, [
  join(root, "node_modules", "@tailwindcss", "cli", "dist", "index.mjs"),
  "--input", join(root, "src", "index.css"),
  "--output", join(root, "build", "tailwind.css"),
  "--minify",
], { stdio: "inherit" });

const css = readFileSync(join(root, "build", "tailwind.css"), "utf8");
writeFileSync(
  join(root, "src", "client", "generated-css.ts"),
  `/* Generated by build.mjs — do not edit. */\nexport const CSS = ${JSON.stringify(css)};\n`,
);

if (cssOnly) {
  console.log("generated src/client/generated-css.ts");
  process.exit(0);
}

const result = await build({
  absWorkingDir: root,
  entryPoints: [join(root, "src", "client", "index.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: ["es2022"],
  jsx: "automatic",
  external: ["react", "react-dom", "react-dom/client", "react/jsx-runtime"],
  alias: { "@": join(root, "src") },
  define: { "process.env.NODE_ENV": "\"production\"" },
  legalComments: "none",
  minify: true,
  write: false,
});

const code = result.outputFiles[0].text;
const artifact = `/**
 * ${pkg} — generated by build.mjs. Do not edit by hand.
 * Registers one lazy factory; the module body runs on first materialization.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`;

writeFileSync(outFile, artifact);
writeFileSync(join(root, "build", "client.preview.js"), artifact);
console.log(`built ${outFile} (${(artifact.length / 1024).toFixed(0)} KiB, css ${(css.length / 1024).toFixed(0)} KiB)`);
